import { z } from 'zod';
import { CAR_ARCHETYPES, CAR_CLASSES, MAX_STAT, SHOWROOM_MODES, type CarModel } from './cars';

const stat = z.number().int().min(1).max(MAX_STAT);

export const carModelSchema = z
  .object({
    id: z.string().regex(/^[a-z0-9_]+$/),
    brand: z.string().min(1),
    name: z.string().min(1),
    year: z.number().int().min(1900).max(2100),
    class: z.enum(CAR_CLASSES),
    archetype: z.enum(CAR_ARCHETYPES),
    stats: z.object({ speed: stat, acceleration: stat, handling: stat, prestige: stat }),
    priceChips: z.number().int().min(1),
    priceStars: z.number().int().min(1).optional(),
    showroom: z.enum(SHOWROOM_MODES),
    editionSize: z.number().int().min(1).optional(),
    styleNumbers: z.array(z.number().int().min(1).max(999)).min(1).optional(),
    season: z.string().regex(/^\d{4}-\d{2}$/).optional(),
  })
  .refine((m) => (m.showroom === 'limited') === (m.editionSize !== undefined), {
    message: 'Тираж задаётся только у моделей с ограниченным тиражом, и у них обязателен',
  });

export const carCatalogSchema = z
  .array(carModelSchema)
  .min(1)
  .refine((ms) => new Set(ms.map((m) => m.id)).size === ms.length, 'id моделей должны быть уникальны');

